"""Generate components/app_pfd/pfd_font_data.c: 8-bit alpha glyphs for the
ASCII range plus every non-ASCII character used in UI sources. Re-run after
changing any on-screen text."""
import glob
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Noto Sans CJK (SIL Open Font License 1.1). Override with PFD_FONT=/path/to/NotoSansCJK-Bold.ttc
FONT = os.environ.get("PFD_FONT", "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc")
SC_INDEX = 2  # Simplified Chinese face
SIZES = [("S", 16), ("M", 20), ("L", 26), ("XL", 30)]
SOURCES = glob.glob(os.path.join(ROOT, "components/app_pfd/*.c")) + \
    glob.glob(os.path.join(ROOT, "components/app_game_runtime/*.c")) + \
    glob.glob(os.path.join(ROOT, "components/app_link/*.c"))
OUT = os.path.join(ROOT, "components/app_pfd/pfd_font_data.c")


def charset():
    chars = {chr(c) for c in range(32, 127)} | {"°"}
    for path in SOURCES:
        if path.endswith("pfd_font_data.c"):
            continue
        with open(path, encoding="utf-8") as f:
            for ch in f.read():
                if ord(ch) > 127:
                    chars.add(ch)
    return sorted(chars, key=ord)


def main():
    chars = charset()
    out = ["// SPDX-License-Identifier: MIT",
           "// Glyph bitmaps rendered from Noto Sans CJK SC (SIL Open Font License 1.1).",
           "// Generated by tools/gen_font.py. Do not edit.",
           '#include "private/pfd_font.h"', ""]
    fonts = []
    for name, px in SIZES:
        font = ImageFont.truetype(FONT, px, index=SC_INDEX)
        ascent, descent = font.getmetrics()
        line_h = ascent + descent
        pixels = bytearray()
        glyphs = []
        for ch in chars:
            bbox = font.getbbox(ch)  # relative to top-left of the line box
            adv = int(round(font.getlength(ch)))
            if ch == " " or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
                glyphs.append((ord(ch), len(pixels), 0, 0, 0, 0, adv))
                continue
            w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
            glyphs.append((ord(ch), len(pixels), w, h, bbox[0], bbox[1], adv))
            pixels += img.tobytes()
        out.append(f"static const uint8_t px_{name}[{len(pixels)}] = {{")
        for i in range(0, len(pixels), 32):
            out.append("    " + ",".join(str(b) for b in pixels[i:i + 32]) + ",")
        out.append("};")
        out.append(f"static const pfd_glyph_t gl_{name}[{len(glyphs)}] = {{")
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        fonts.append(f"    {{gl_{name}, {len(glyphs)}, px_{name}, {line_h}, {px}}},")
    out.append("const pfd_font_t pfd_fonts[PFD_FONT_COUNT] = {")
    out += fonts
    out.append("};")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(chars)} chars, {len(SIZES)} sizes -> {OUT}")


if __name__ == "__main__":
    main()
